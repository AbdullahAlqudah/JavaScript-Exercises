const average = (...grades) => grades.length ? grades.reduce((sum, grade) => sum + grade, 0) / grades.length : 0;
const grades = new Map();
grades.set(101, 80);
grades.set(102, 90);
grades.set(103, 75);
grades.set(104, 88);
grades.set(105, 95);
grades.set(101, 85);
